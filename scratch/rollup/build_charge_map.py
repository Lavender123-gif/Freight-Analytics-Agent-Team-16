"""T14-05: write config/charge_map.yaml, the deterministic mapping from our internal charge codes to the client's
Addenda B names (T13 option 3, decided 2026-11-15), and the git-ignored backup table of unused road names.

Inputs: the hand-made mapping docs/deliverables/T13-taxonomy-mapping/scripts/t13_mapping.py (tracked) and the
extracted list data/interim/deliverables/T13/addenda_b_names.csv / unused_names.csv (git-ignored, from the client's
PDF). Only the names our codes use, their EDI codes and their parents go into the tracked YAML; the 128 'road
possible' names go to data/interim/charge_map/backup_names.csv (git-ignored), never into the prompt.
Run: uv run python scratch/rollup/build_charge_map.py
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

import yaml

from freight_lineitems.config import CODES, CONFIG_DIR, ROOT

sys.path.insert(0, str(ROOT / "docs" / "deliverables" / "T13-taxonomy-mapping" / "scripts"))
import t13_mapping as m  # noqa: E402

T13 = ROOT / "data" / "interim" / "deliverables" / "T13"
OUT = CONFIG_DIR / "charge_map.yaml"
BACKUP = ROOT / "data" / "interim" / "charge_map" / "backup_names.csv"

# short English labels for display (our own wording; the internal code stays the identity)
LABEL = {
    "LINEHAUL.MINIMUM": "minimum charge", "RATE_CORRECTION.FUEL_TIER": "fuel tier correction",
    "RATE_CORRECTION.BASE_RATE": "base rate correction", "RATE_CORRECTION.WEIGHT": "weight correction",
    "RATE_CORRECTION.ZONE_FACTOR": "zone factor correction", "PENDING.PURCHASED_TRANSPORTATION": "purchased transportation",
    "RATE_CORRECTION.CONTRACT_GENERAL": "contract rate difference", "ACCESSORIAL.LIMITED_ACCESS": "limited access",
    "ACCESSORIAL.ROAD_CLOSURE": "road closure surcharge", "DETENTION_STORAGE.DWELL": "dwell",
    "ACCESSORIAL.SPECIAL_DELIVERY": "SPECIAL DELIVERY (generic)", "ACCESSORIAL.PROTECT_FROM_FREEZE": "PROTECT FROM FREEZE (generic)",
    "ACCESSORIAL.REWEIGH": "REWEIGH / INSPECTION (generic)", "DETENTION_STORAGE.DRIVER_DETENTION": "DRIVER DETENTION (generic)",
    "DETENTION_STORAGE.EQUIPMENT_DETENTION": "EQUIPMENT DETENTION (generic)",
    "DETENTION_STORAGE.CONTAINER_PER_DIEM": "CONTAINER PER DIEM (generic)", "DRAYAGE.PORT_FEE": "PORT FEE (generic)",
    "TAX.PST": "PST / QST (generic)", "TAX.UNSPECIFIED": "TAX (type not stated)", "OTHER": "OTHER",
}
REL = {m.EXACT: "EXACT", m.APPROX: "APPROX", m.ONE_TO_MANY: "ONE_TO_MANY", m.CHILD: "CHILD"}
# C5 (user 2026-11-15): the definition the client-rooted prompt layout (v1.3b) shows instead of taxonomy.yaml's
PROMPT_DEFINITION = {
    "PENDING.PURCHASED_TRANSPORTATION": "Purchased transportation surcharge or fee. The client's contact thinks it may be "
        "line haul keyed in by mistake (a guess, not confirmed). Use this code for it in any spelling; do not explain it.",
}


def main() -> None:
    with (T13 / "addenda_b_names.csv").open() as f:
        edi = {r["name"]: r["edi_codes"].split() for r in csv.DictReader(f)}
    assert set(m.MAPPING) == set(CODES), sorted(set(m.MAPPING) ^ set(CODES))
    codes = {}
    for code, (typ, names, ext_parent, _why) in m.MAPPING.items():
        if typ == m.NONE:
            rel = "EXTENSION" if ext_parent else "TOP_LEVEL"
            parent, cands = ext_parent, []
            display = f"{ext_parent} / {LABEL[code]} (extension, not on the list)" if ext_parent else LABEL[code]
        elif typ == m.CHILD:
            rel, parent, cands = "CHILD", names[0], names
            display = f"{names[0]} / {LABEL[code]} (sub-item)"
        elif typ == m.ONE_TO_MANY:
            rel, parent, cands = "ONE_TO_MANY", None, names
            display = LABEL[code]
        else:
            rel, parent, cands = REL[typ], None, names
            display = names[0]
        codes[code] = {"relation": rel, "client_name": display, "parent": parent, "client_names": cands,
                       "edi_candidates": sorted({c for n in cands for c in edi[n]})}
        if code in PROMPT_DEFINITION:
            codes[code]["prompt_definition"] = PROMPT_DEFINITION[code]
    roots = sorted({n for c in codes.values() for n in c["client_names"]} | {c["parent"] for c in codes.values() if c["parent"]})
    head = ("# Charge-code mapping (task 14 / T14-05; T13 option 3, user decision 2026-11-15). Generated by\n"
            "# scratch/rollup/build_charge_map.py from the hand-made T13 mapping; do not edit by hand.\n"
            "# Our internal codes stay the identity everywhere (comparisons, tests, mock expectations); this file only\n"
            "# adds the client's Addenda B name and the candidate EDI codes to the output. Relations:\n"
            "#   EXACT / APPROX  one client name; ONE_TO_MANY  several client names fit and the list does not say which:\n"
            "#   all candidates are listed and none is chosen (client_name is our generic entry, client_names the reference);\n"
            "#   CHILD  sub-item under a wider client entry (purchased transportation, rate and weight corrections, minimum);\n"
            "#   EXTENSION  not on the list, shown under the nearest entry (assumption, not confirmed by the client);\n"
            "#   TOP_LEVEL  not on the list and not placed under anything (tax type not stated, OTHER).\n"
            "# edi_candidates: every EDI code the list gives for the name(s); a CHILD carries its parent's codes. When a\n"
            "# name has several codes, all are listed and none is chosen (assumption, report section 'Assumptions').\n")
    body = {"version": "charge-map-v1-2026-11-15", "source": "Addenda B accessorial list (client, 2026-11-13); T13 mapping",
            "client_roots_used": len(roots), "codes": codes}
    OUT.write_text(head + yaml.safe_dump(body, sort_keys=False, allow_unicode=True, width=140))
    BACKUP.parent.mkdir(parents=True, exist_ok=True)
    with (T13 / "unused_names.csv").open() as f, BACKUP.open("w", newline="") as g:
        rows = [r for r in csv.DictReader(f) if r.get("group") == "ROAD_POSSIBLE"]
        w = csv.DictWriter(g, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    print(f"{OUT.relative_to(ROOT)}: {len(codes)} codes, {len(roots)} client names used; backup table: {len(rows)} names")


if __name__ == "__main__":
    main()
