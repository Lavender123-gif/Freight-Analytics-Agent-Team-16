"""C1 deliverable: the diagnostics catalog (scratch/prototype/diagnostics_catalog.yaml) is complete and consistent.

Run from repo root: sh scratch/deliverables/run.sh C1_catalog_check.py
Checks: every catalog entry has its fixed texts; every code the prototype source emits is in the catalog; every
record-only code has a rules.yaml entry (and vice versa); every code that fired on the 908 dev events is in the
catalog; notices sent to carriers use only catalog text. Writes the rendered catalog. No LLM calls.
"""

from __future__ import annotations

import re
import subprocess
import sys
from collections import Counter

from _shared import PROTO, md_table, results_dir, run_code_only
from config import CATALOG, RULES

FOLDER = "C1-diagnostics-catalog"
codes = [c for c in CATALOG if c != "version"]
REQUIRED = ["object", "trigger", "evidence", "step", "handling"]
# return-type codes go back to the model only and never reach a reviewer (02 §4.2), so only record-only codes need reviewer text
missing_fields = [(c, k) for c in codes for k in REQUIRED + (["reviewer"] if CATALOG[c]["handling"] == "record" else [])
                  if CATALOG[c].get(k) in (None, "")]
bad_handling = [c for c in codes if CATALOG[c]["handling"] not in ("return", "record")]
bad_name = [c for c in codes if not re.fullmatch(r"(REC|NUM|ITEM|CLAIM|HIST|RUN)\.[A-Z]+\.[A-Z0-9_]+", c)]
record_codes = {c for c in codes if CATALOG[c]["handling"] == "record"}
return_codes = {c for c in codes if CATALOG[c]["handling"] == "return"}
rules_codes = set(RULES["flags"])
carrier_fix_wo_acceptance = [c for c in codes if bool(CATALOG[c].get("carrier_fix")) != bool(CATALOG[c].get("acceptance"))]

src = "\n".join(p.read_text() for p in PROTO.glob("*.py") if p.name not in ("prototype_checks.py", "walkthrough.py"))
emitted = set(re.findall(r'"((?:REC|NUM|ITEM|CLAIM|HIST|RUN)\.[A-Z]+\.[A-Z0-9_]+)"', src))
mentioned_not_in_catalog = sorted(emitted - set(codes))
catalog_not_in_source = sorted(set(codes) - emitted)

rows, ev, records = run_code_only()
fired = Counter(c for r in records for c in {d.code for d in r.diagnostics})
fired_unknown = sorted(set(fired) - set(codes))
notice_texts = {t for r in records if r.reject_draft for t in r.reject_draft.required_changes + r.reject_draft.acceptance_criteria}
catalog_texts = {CATALOG[c].get(k) for c in codes for k in ("carrier_fix", "acceptance")}
notice_not_from_catalog = notice_texts - catalog_texts

checks = [
    ["catalog entries", len(codes), "61 (02 §4.3)", len(codes) == 61],
    ["  return / record", f"{len(return_codes)} / {len(record_codes)}", "15 / 46", (len(return_codes), len(record_codes)) == (15, 46)],
    ["entries missing a required field (reviewer text required for record-only codes)", len(missing_fields), "0", not missing_fields],
    ["entries with invalid handling", len(bad_handling), "0", not bad_handling],
    ["codes not in OBJECT.SUBCLASS.TYPE form", len(bad_name), "0", not bad_name],
    ["record-only codes without a rules.yaml entry", len(record_codes - rules_codes), "0", not (record_codes - rules_codes)],
    ["rules.yaml entries not in the catalog", len(rules_codes - set(codes)), "0", not (rules_codes - set(codes))],
    ["return codes that (wrongly) have a rules.yaml entry", len(return_codes & rules_codes), "0", not (return_codes & rules_codes)],
    ["carrier_fix without acceptance (or vice versa)", len(carrier_fix_wo_acceptance), "0", not carrier_fix_wo_acceptance],
    ["codes in prototype source not in the catalog", len(mentioned_not_in_catalog), "0", not mentioned_not_in_catalog],
    ["codes fired on 908 dev events not in the catalog", len(fired_unknown), "0", not fired_unknown],
    ["notice / draft sentences not taken from the catalog", len(notice_not_from_catalog), "0", not notice_not_from_catalog],
]

rc = subprocess.run([sys.executable, str(PROTO / "render_catalog.py")], capture_output=True, text=True)
res = results_dir(FOLDER)
(res / "catalog_rendered.md").write_text("# Diagnostics catalog (rendered by scratch/prototype/render_catalog.py)\n" + rc.stdout)

by_obj = Counter(c.split(".")[0] for c in codes)
summary = ["# C1 diagnostics catalog — results\n",
           "Generated by `sh scratch/deliverables/run.sh C1_catalog_check.py`. Dev split for the 'fired' counts (908 events, "
           "code-only, no step 3). Not the test set.\n",
           md_table(["check", "value", "expected", "pass"], [[a, b, c, "PASS" if d else "FAIL"] for a, b, c, d in checks]),
           f"\n`render_catalog.py` exit code: {rc.returncode} (it asserts every record-only code has a rules entry). "
           f"stderr: {rc.stderr.strip()}\n",
           "\n## Entries per object\n", md_table(["object", "entries"], sorted(by_obj.items())),
           "\n## Codes that fired on the dev split (code-only run)\n",
           md_table(["code", "events"], [[f"`{c}`", n] for c, n in sorted(fired.items())]),
           f"\nCatalog codes never fired in the code-only run: {len(set(codes) - set(fired))} "
           "(most need step 3 output; see 02 §7.1).\n",
           "\n## Catalog codes not found as a literal in prototype source (emitted indirectly or not yet implemented)\n",
           ", ".join(f"`{c}`" for c in catalog_not_in_source) or "none", "\n"]
(res / "summary.md").write_text("\n".join(summary))

ex = ["REC.TEXT.NUMBERS_ONLY", "NUM.JUDGMENT.DOLLAR_EXCLUDED", "CLAIM.RECON.DELTA_COUNTS_TOTAL_TWICE",
      "HIST.AMOUNT.EQUALS_EARLIER_DELTA", "CLAIM.RECON.SUM_MISMATCH"]
ex_rows = [[f"`{c}`", CATALOG[c]["trigger"], "退回" if CATALOG[c]["handling"] == "return" else "只记录",
            f"{RULES['flags'][c]['role']}" if c in RULES["flags"] else "不生成 flag", CATALOG[c]["reviewer"] or "无",
            CATALOG[c].get("carrier_fix") or "无"] for c in ex]
(res / "examples.md").write_text("\n".join([
    "# C1 diagnostics catalog — examples\n",
    "Five entries: a finding becomes a diagnostic with a fixed reviewer text and, where the carrier can fix it, a fixed request.\n",
    md_table(["code", "trigger", "handling", "escalation role", "to reviewer", "to carrier"], ex_rows)]))
print("\n".join(summary))
