"""A1 deliverable: verify the shipment-level dev/test split.

Run from repo root: uv run python scratch/deliverables/A1_split_check.py

The only exception to "do not open the test set" in task 03, approved by the project owner: test.csv is read with
usecols=[SHIPMENT_GID] for the overlap and row-count checks (as tests/test_data_split.py already does). No other
test column is read and no ID is printed or written; only counts and pass/fail.
"""

from __future__ import annotations

import re
import subprocess
import sys

import pandas as pd

from _shared import DEV_CSV, ROOT, md_table, results_dir

FOLDER = "A1-dev-test-split"
TEST_CSV = ROOT / "data" / "processed" / "test.csv"
RAW_ROW_COUNT = 1347  # from tests/test_data_split.py

# 1. existing unit tests (3 synthetic + 2 that read only the test ID column)
p = subprocess.run(["uv", "run", "pytest", "tests/test_data_split.py", "-q"], cwd=ROOT, capture_output=True, text=True)
m = re.search(r"(\d+) passed", p.stdout)
n_passed = int(m.group(1)) if m else 0
n_failed = int(m.group(1)) if (m := re.search(r"(\d+) failed", p.stdout)) else 0

# 2. counts
dev = pd.read_csv(DEV_CSV, dtype=str, usecols=["SHIPMENT_GID", "Carrier"])
test_ids = pd.read_csv(TEST_CSV, dtype=str, usecols=["SHIPMENT_GID"])["SHIPMENT_GID"]
overlap = len(set(dev.SHIPMENT_GID) & set(test_ids))
per_ship = dev.groupby("SHIPMENT_GID").Carrier.nunique()

checks = [
    ["pytest tests/test_data_split.py", f"{n_passed} passed, {n_failed} failed", "5 passed", n_passed == 5 and n_failed == 0],
    ["dev rows", len(dev), "953 (02 §0)", len(dev) == 953],
    ["dev shipments", dev.SHIPMENT_GID.nunique(), "813 (02 §0)", dev.SHIPMENT_GID.nunique() == 813],
    ["test rows", len(test_ids), f"{RAW_ROW_COUNT} - 953 = {RAW_ROW_COUNT - 953}", len(test_ids) == RAW_ROW_COUNT - 953],
    ["test shipments", test_ids.nunique(), "-", True],
    ["shipments in both splits", overlap, "0", overlap == 0],
    ["dev rows + test rows", len(dev) + len(test_ids), str(RAW_ROW_COUNT), len(dev) + len(test_ids) == RAW_ROW_COUNT],
    ["dev shipments with >1 carrier", int((per_ship > 1).sum()), "0", int((per_ship > 1).sum()) == 0],
]
test_share = test_ids.nunique() / (test_ids.nunique() + dev.SHIPMENT_GID.nunique())

# 3. dev-side carrier distribution by rank (no carrier codes)
by_car = dev.groupby("Carrier").SHIPMENT_GID.nunique().sort_values(ascending=False)
rank_rows = [[f"#{i + 1}", n, int((dev.Carrier == c).sum())] for i, (c, n) in enumerate(by_car.items())]

out = ["# A1 split check — results\n",
       "Generated by `uv run python scratch/deliverables/A1_split_check.py`. Counts only; no IDs.\n",
       md_table(["check", "value", "expected", "pass"], [[a, b, c, "PASS" if d else "FAIL"] for a, b, c, d in checks]),
       f"\nTest share of shipments: {test_share:.1%} (target 30% within carriers that have >= 4 shipments; "
       "carriers with < 4 shipments go entirely to dev).\n",
       "\n## Dev split by carrier rank (carrier codes withheld)\n",
       md_table(["carrier rank", "dev shipments", "dev rows"], rank_rows)]
(results_dir(FOLDER) / "summary.md").write_text("\n".join(out))
print("\n".join(out))
sys.exit(0 if all(c[3] for c in checks) else 1)
