"""B02 deliverable: step 2, number recognition with the coverage check.

Run from repo root: sh scratch/deliverables/run.sh B02_number_parse.py
Dev split only. Runs parse() on every distinct redacted text (529, incl. the empty text) and the step-2
diagnostics on all 908 events. Compares against 02 §7.2. No LLM calls.
"""

from __future__ import annotations

import json
from collections import Counter

from _shared import md_table, results_dir, rowlevel_dir, run_code_only, safe_for_docs, unify_placeholders
from number_parse import parse

FOLDER = "B02-number-parse"
EXPECTED_EVENTS = {"NUM.PARSE.UNRECOGNIZED_REGION": 1, "NUM.PARSE.SPACE_MERGED": 99, "NUM.PARSE.UNUSUAL_DECIMALS": 1,
                   "NUM.PARSE.LEADING_DOT": 7, "NUM.PARSE.MINUS_ADJACENT": 2, "REC.TEXT.NUMBERS_ONLY": 6,
                   "REC.TEXT.NO_NUMBER": 1, "REC.TEXT.DATE_AFTER_EVENT": 6}

rows, ev, records = run_code_only()
texts = sorted({r.text.redacted for r in records})
parsed = {t: parse(t) for t in texts}
n_cov = sum(p.coverage_ok for p in parsed.values())
n_num = sum(len(p.numbers) for p in parsed.values())
n_dates = sum(len(p.dates) for p in parsed.values())
n_unrec = sum(len(p.unrecognized) for p in parsed.values())
feat = Counter()
for p in parsed.values():
    for n in p.numbers:
        feat["has_dollar"] += n.has_dollar
        feat["space_merged"] += n.space_merged
        feat["leading_dot"] += n.leading_dot
        feat["trailing_dot"] += n.trailing_dot
        feat["minus_adjacent"] += n.minus_before == "adjacent"
        feat["unit_hint"] += n.unit_hint is not None

ev_counts = Counter()
for r in records:
    for c in {d.code for d in r.diagnostics}:
        if c in EXPECTED_EVENTS:
            ev_counts[c] += 1
diag_rows = [[f"`{c}`", ev_counts[c], x, "PASS" if ev_counts[c] == x else "DIFF"] for c, x in EXPECTED_EVENTS.items()]

checks = [["distinct texts (incl. empty)", len(texts), "529 (02 §7.2)", len(texts) == 529],
          ["texts passing the coverage check", n_cov, f"all {len(texts)}", n_cov == len(texts)]]


# examples: one per interesting feature, screened for IDs
def first(pred):
    for t, p in parsed.items():
        if t and pred(p) and safe_for_docs(t) and len(t) < 150:
            return t, p
    return None


wanted = [("space-merged amount", lambda p: any(n.space_merged and n.has_dollar for n in p.numbers)),
          ("leading dot", lambda p: any(n.leading_dot for n in p.numbers)),
          ("unrecognized region", lambda p: p.unrecognized),
          ("date + weight + amount", lambda p: p.dates and any(n.unit_hint for n in p.numbers) and any(n.has_dollar for n in p.numbers)),
          ("minus adjacent", lambda p: any(n.minus_before == "adjacent" for n in p.numbers))]
ex_rows = []
for label, pred in wanted:
    hit = first(pred)
    if hit:
        t, p = hit
        ex_rows.append([label, f"`{unify_placeholders(t)}`", f"`{unify_placeholders(p.marked_text)}`",
                        "; ".join(f"{n.id}={n.value}" + ("$" if n.has_dollar else "") + (f" ({n.unit_hint})" if n.unit_hint else "")
                                  for n in p.numbers)])

res = results_dir(FOLDER)
summary = ["# B02 number parse — results\n",
           "Generated by `sh scratch/deliverables/run.sh B02_number_parse.py`. Dev split (908 events, 529 distinct texts). Not the test set.\n",
           md_table(["check", "value", "expected", "pass"], [[a, b, c, "PASS" if d else "FAIL"] for a, b, c, d in checks]),
           f"\nTokens over the 529 distinct texts: {n_num} numbers, {n_dates} dates/times, {n_unrec} unrecognized regions.\n",
           md_table(["number feature", "count (distinct texts)"], sorted(feat.items())),
           "\n## Step-2 diagnostics on 908 events vs 02 §7.2\n",
           md_table(["code", "events", "02 §7.2", "check"], diag_rows)]
(res / "summary.md").write_text("\n".join(summary))
(res / "examples.md").write_text("\n".join([
    "# B02 number parse — examples (before → after)\n",
    "Before: redacted text. After: marked text given to the model; every number has an id, dates are `D`, "
    "unclaimed digits are `?` regions. Screened for IDs and carrier codes.\n",
    md_table(["feature", "text (before)", "marked text (after)", "number table (value, $, unit)"], ex_rows)]))

rl = rowlevel_dir("B02")
with open(rl / "parsed_texts.jsonl", "w") as f:
    for t, p in parsed.items():
        f.write(json.dumps({"text": t, "parse": p.model_dump(mode="json")}) + "\n")
print("\n".join(summary))
print(f"examples: {len(ex_rows)}; row-level -> {rl}")
