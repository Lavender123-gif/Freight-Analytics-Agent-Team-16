"""Generate docs/rule_sheet.en.md: the rules of the system in plain English, for reviewers and the client.

Severity, subsumption and every number come from config/rules.yaml; the wording of each flag comes from
config/rule_sheet_text.en.yaml. So the sheet cannot say anything different from what the code does, and it is
regenerated after any rule change.

Usage (from the repository root):
  uv run python scratch/rules/build_rule_sheet.py            # write docs/rule_sheet.en.md
  uv run python scratch/rules/build_rule_sheet.py --check    # exit 1 if wording is missing or stale, or the sheet is out of date
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
RULES = ROOT / "config" / "rules.yaml"
TEXT = ROOT / "config" / "rule_sheet_text.en.yaml"
OUT = ROOT / "docs" / "rule_sheet.en.md"

SEVERITY_LABEL = {"attention": "Attention", "return": "Return", "info": "Info"}
GROUPS = [("REC.TEXT", "The text of the note"), ("REC.FIELD", "The other fields of the record"),
          ("NUM", "Numbers found in the text"), ("ITEM", "Line items (charge, amount, tax, basis)"),
          ("CLAIM", "The claim: what the reading counts"), ("SHIP", "Copies and the shipment roll-up"),
          ("RUN", "The model run itself")]


def problems(rules: dict, text: dict) -> list[str]:
    """Wording missing for a flag, wording without a flag, wording without both fields."""
    out = [f"no wording for flag {c}" for c in rules["flags"] if c not in text]
    out += [f"wording for {c} but no such flag in rules.yaml" for c in text if c not in rules["flags"]]
    out += [f"{c}: needs non-empty `when` and `look`" for c, v in text.items() if not (v or {}).get("when") or not (v or {}).get("look")]
    out += [f"subsumption names unknown flag {c}" for c, subs in rules.get("subsumption", {}).items()
            for c in [c, *subs] if c not in rules["flags"]]
    return out


def _cell(s: str) -> str:
    return " ".join(str(s).split()).replace("|", "\\|")


def group_of(code: str) -> str:
    return next(g for prefix, g in GROUPS if code == prefix or code.startswith(prefix + "."))


def render(rules: dict, text: dict) -> str:
    flags = rules["flags"]
    n = {s: sum(1 for f in flags.values() if f["severity"] == s) for s in SEVERITY_LABEL}
    L = ["# Rule sheet",
         "",
         "*Generated by `scratch/rules/build_rule_sheet.py` from `config/rules.yaml` and `config/rule_sheet_text.en.yaml`. "
         "Do not edit by hand: change the rules or the wording, then regenerate.*",
         "",
         f"Rules version: `{rules['version']}`. {len(flags)} flags: {n['attention']} Attention, {n['return']} Return, {n['info']} Info.",
         "",
         "## What the system does and does not do",
         "",
         "The system reads each carrier explanation, turns it into line items, checks the result and raises flags. "
         "**It never decides whether a charge is justified or should be paid.** Every record goes to a reviewer, "
         "whatever its colour. The buttons on the review screen only record the reviewer's own decision. The model is never told how "
         "its reading compares with any amount in the Excel row (Delta, invoice amount); those amounts are used only to evaluate the system.",
         "",
         "## How the colour of a record is decided",
         "",
         "The colour is computed from the flags of the record, in this order. It is never computed from how confident the model says it is.",
         "",
         "1. If any flag has severity **Attention**: **Human review**.",
         "2. Otherwise, if any flag has severity **Return**: **Return suggested**.",
         "3. Otherwise: **Passed checks**.",
         "",
         "**Info** flags are shown to the reviewer and never change the colour. \"Passed checks\" means the reading passed the checks and "
         "has no flag a person must look at. It does not mean the reading is correct or the charge is payable.",
         "",
         "A **return** is suggested only where code alone can decide: empty text, or text with numbers but no letters. "
         "Anything that depends on the model's reading goes to a person, because keeping a correct claim out of the process is the worst failure.",
         ""]
    sub = rules.get("subsumption", {})
    if sub:
        L += ["### Flags shown as Info when another flag already explains them", "",
              "When one of the flags on the right is present on a record, the flag on the left is shown as Info, because the flag on the right "
              "is decided by code alone and already implies it.", "",
              "| Flag | Shown as Info when this is present |", "|---|---|"]
        L += [f"| `{c}` | {', '.join(f'`{s}`' for s in subs)} |" for c, subs in sub.items()]
        L.append("")
    L += ["## The flags", "", "Severity: Attention = a person must look; Return = a return to the carrier can be suggested; Info = shown only.", ""]
    for _, title in GROUPS:
        codes = [c for c in flags if group_of(c) == title]
        if not codes:
            continue
        L += [f"### {title}", "", "| Flag | Severity | When it is raised | What to look at |", "|---|---|---|---|"]
        for c in codes:
            sev = SEVERITY_LABEL[flags[c]["severity"]]
            look = text[c]["look"]
            if flags[c].get("carrier_fix"):
                look += f" Wording in a return draft: \"{flags[c]['carrier_fix']}\""
            L.append(f"| `{c}` | {sev} | {_cell(text[c]['when'])} | {_cell(look)} |")
        L.append("")
    a, t, x, inj, ro = rules["agent"], rules["tolerances"], rules["exclusion_basis"]["categories"], rules["injection"], rules["rollup"]
    L += ["## Settings behind the rules", "",
          f"- The model gets at most **{a['max_turns']}** calls per record, and **{a['max_repair_rounds']}** resubmissions after a failed mandatory check.",
          f"- The model may report at most **{a['max_uncertainty_reports']}** doubts per record.",
          f"- Two amounts count as equal when they differ by at most **{t['amount_abs']}**; a tax amount agrees with base times rate within **{t['tax_abs']}**; "
          f"a calculation written in the text holds within **{t['relation_abs']}**.",
          f"- In the shipment roll-up, an amount that is **{ro['ratio_min']} to {ro['ratio_max']}** times an earlier amount is treated as a restatement of it.",
          f"- A date in the text counts as \"after the event\" when it is more than **{t['text_date_after_event_days']}** day(s) later than the event date.",
          f"- Text is checked for instruction-like wording with **{len(inj['patterns'])}** patterns, and texts longer than **{inj['max_length']}** characters are flagged.",
          "", "### Words accepted as a reason to leave an amount out",
          "", "A dollar amount may be left out of the claim only if the words the model quotes contain one of these. Otherwise `NUM.JUDGMENT.EXCLUSION_BASIS_UNLISTED` is raised.", "",
          "| Reason | Words |", "|---|---|"]
    L += [f"| {k.replace('_', ' ')} | {_cell(', '.join(map(str, v)))} |" for k, v in x.items()]
    return "\n".join(L) + "\n"


def main(argv: list[str]) -> int:
    rules, text = yaml.safe_load(RULES.read_text()), yaml.safe_load(TEXT.read_text())
    errs = problems(rules, text)
    if errs:
        print("\n".join(errs))
        return 1
    sheet = render(rules, text)
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != sheet:
            print(f"{OUT.relative_to(ROOT)} is out of date: run scratch/rules/build_rule_sheet.py")
            return 1
        print("rule sheet: wording complete and file up to date")
        return 0
    OUT.write_text(sheet)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rules['flags'])} flags)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
